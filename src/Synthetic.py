from __future__ import annotations
from pathlib import Path

import numpy as np
import pandas as pd

from .DataLoader import HourlyCalendar, FIELDS


def MakeSynthetic(cfg: dict, out_dir: Path, seed: int = 11, n_cointegrated: int = 3) -> dict:
    rng = np.random.default_rng(seed)
    cal = HourlyCalendar(cfg)
    n = len(cal)
    assets = cfg["data"]["assets"]
    market = np.cumsum(rng.normal(0, 0.004, n))
    logp = {}
    for i, a in enumerate(assets):
        beta_m = rng.uniform(0.6, 1.4)
        idio = np.cumsum(rng.normal(0, 0.003, n))
        logp[a] = np.log(rng.uniform(0.5, 500)) + beta_m * market + idio
    # make pairs (assets[2k+1] follows assets[2k]) cointegrated with an OU spread
    for k in range(n_cointegrated):
        y, x = assets[2 * k], assets[2 * k + 1]
        b = rng.uniform(0.8, 1.6)
        spread = np.zeros(n)
        phi, sig = 0.97, 0.01          # half-life ~ 23h
        eps = rng.normal(0, sig, n)
        for t in range(1, n):
            spread[t] = phi * spread[t - 1] + eps[t]
        logp[x] = 0.3 + b * logp[y] + spread
    close = pd.DataFrame({a: np.exp(logp[a]) for a in assets}, index=cal)
    open_ = close.shift(1)
    open_.iloc[0] = close.iloc[0]
    open_ = open_ * np.exp(rng.normal(0, 0.0005, close.shape))
    hi = np.maximum(open_, close) * (1 + np.abs(rng.normal(0, 0.001, close.shape)))
    lo = np.minimum(open_, close) * (1 - np.abs(rng.normal(0, 0.001, close.shape)))
    vol = pd.DataFrame(rng.uniform(500, 5000, close.shape), index=cal, columns=assets)
    qvol = vol * close
    frames = {"open": open_, "high": hi, "low": lo, "close": close, "volume": vol, "quote_volume": qvol}
    # inject missing hours (NaN, never filled)
    for a in assets:
        miss = rng.choice(n, size=int(0.002 * n), replace=False)
        for f in FIELDS:
            frames[f].iloc[miss, frames[f].columns.get_loc(a)] = np.nan
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for f in FIELDS:
        fr = frames[f].copy()
        fr.index.name = "timestamp"
        fr.to_csv(out_dir / f"{f}.csv.gz")
    (out_dir / "README_SYNTHETIC.txt").write_text(
        "SYNTHETIC DATA. Generated by src/synthetic.py to test the pipeline. Not market data.\n")
    return frames